"""docs/APP.md from the snapshots and checks.   Run: python -m dashboards.report_phase8 [--check]"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC, SNAP = ROOT / "docs" / "APP.md", ROOT / "dashboards" / "snapshots"


def render() -> str:
    m = json.loads((SNAP / "manifest.json").read_text(encoding="utf-8"))
    url_file = ROOT / "dashboards" / "app_url.txt"
    url = url_file.read_text(encoding="utf-8").strip() if url_file.exists() else ""
    sc = json.loads((ROOT / "dashboards" / "phase8_scorecard.json").read_text(encoding="utf-8"))
    L = ["# Phase 8: the Streamlit app", "", "_Generated by `python -m dashboards.report_phase8`. Do not edit by hand._", "",
         f"**Live app:** {url}" if url else "**Live app:** not deployed yet.", "",
         "The app shows the project to someone who will not install anything. It reads only the committed snapshot files in `dashboards/snapshots/`: "
         "it never calls the Claude API (recorded answers are replayed) and never connects to a database. Run it locally with "
         "`.venv-app\\Scripts\\streamlit run app/streamlit_app.py` after `pip install -r app/requirements.txt`.", "",
         "## Pages", "", *[f"- {p}" for p in sc["pages"]], "",
         "## Snapshots", "", "| File | Rows | sha256 (first 12) |", "|---|---|---|",
         *[f"| {k} | {v['rows']} | `{v['sha256'][:12]}` |" for k, v in m["files"].items()], "",
         f"Data checksum: `{m['data_checksum']}` (also shown on the app's About page). Made by `python -m dashboards.export_snapshots` from the local database and "
         "these results files: " + ", ".join(f"`{s}`" for s in m["sources"]) + ".", "",
         "## Checks", "", "- `python -m dashboards.verify_phase8 [--local]`: snapshots against the manifest, the results files and (local) separate SQL; no API, database or key code in the app; no contact details; planted bugs.",
         "- `tests/app/` (run in the app's own environment, as CI does on Python 3.12-3.14): every page and recorded answer renders, numbers on screen equal values recomputed from the files, required warnings are present, memory refuses personal data.", ""]
    return "\n".join(L)


def main(check: bool) -> int:
    doc = render()
    if check:
        ok = DOC.exists() and DOC.read_text(encoding="utf-8") == doc
        print("APP.md is " + ("up to date" if ok else "stale: run python -m dashboards.report_phase8"))
        return 0 if ok else 1
    DOC.write_text(doc, encoding="utf-8", newline="\n")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    sys.exit(main(ap.parse_args().check))
