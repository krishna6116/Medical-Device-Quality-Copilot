def main(check: bool) -> int:
    doc = render()
    if check:
        ok = DOC.exists() and DOC.read_text(encoding="utf-8") == doc
        print("SAFETY_AND_DRIFT.md is " + ("up to date" if ok else "stale: run python -m mdqc.report_phase7"))
        return 0 if ok else 1
    DOC.write_text(doc, encoding="utf-8", newline="\n")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    sys.exit(main(ap.parse_args().check))
