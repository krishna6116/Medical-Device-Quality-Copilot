"""Render docs/PIPELINE.md from results/phase2/ (never hand-typed numbers).

Run:  python -m mdqc.report_phase2 [--check]
Sources: config/phase2_criteria.json, config/manufacturer_aliases.json, results/phase2/load_summary.json,
results/phase2/verify_phase2.json.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "PIPELINE.md"


def load(rel):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def n(x):
    return f"{x:,}" if isinstance(x, int) else str(x)


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


ER = """```mermaid
erDiagram
    dim_product_code ||--o{ fact_report : "product_code"
    dim_manufacturer ||--o{ fact_report : "manufacturer_id"
    dim_date ||--o{ fact_report : "date_received"
    fact_report ||--o{ report_device : "mdr_report_key"
    fact_report ||--o{ report_problem : "mdr_report_key"
    fact_report ||--o{ report_patient_problem : "mdr_report_key"
    fact_report ||--o{ report_text : "mdr_report_key"
    dim_product_code ||--o{ fact_recall : "product_code"
    dim_manufacturer ||--o{ fact_recall : "manufacturer_id"
    fact_report ||--o{ report_recall_link : "mdr_report_key"
    fact_recall ||--o{ report_recall_link : "product_res_number"
```"""


def render() -> str:
    crit, aliases = load("config/phase2_criteria.json"), load("config/manufacturer_aliases.json")
    ls, ver = load("results/phase2/load_summary.json"), load("results/phase2/verify_phase2.json")
    c, s = ls["counts"], ls["stats"]
    p1 = load("results/phase1/eda_summary.json")
    p2 = next(x for x in ver["checks"] if x["id"] == "P2")["detail"]["rows_compared"]
    rows_checked = sum(p2.values())
    passed = sum(x["pass"] for x in ver["checks"])
    L = []
    a = L.append
    a("# Phase 2: PostgreSQL pipeline\n")
    a("> Generated by `python -m mdqc.report_phase2` from `results/phase2/`. Do not edit by hand.\n")
    a(f"**What it does:** turns the {n(sum(v for k, v in c['raw_records'].items() if k.startswith('events_')))} raw "
      f"adverse-event reports and {n(sum(v for k, v in c['raw_records'].items() if k.startswith('recalls_')))} recall "
      "records from Phase 1 into a cleaned star schema in PostgreSQL (database `mdqc`, schema `core`), drops personal "
      "fields, puts every record that breaks a rule into a quarantine table with the rule it broke, merges manufacturer "
      "names into parent companies, and links reports to recalls.\n")
    a(f"**Verification:** `python -m mdqc.verify_phase2` rebuilds every table from the raw files with separate code and "
      f"compares every row and column: **{passed}/{len(ver['checks'])} criteria pass** (evidence "
      f"`results/phase2/verify_phase2.json`, checked {ver['checked_utc']}). Rules and criteria were committed before "
      "the first load (`config/phase2_criteria.json`, `config/manufacturer_aliases.json`).\n")

    a("## Schema\n")
    a(ER + "\n")
    a("Two facts: one row per report (`fact_report`) and one per recall record (`fact_recall`). Report details that "
      "repeat (devices, FDA problem terms, patient problem terms, narrative texts) sit in child tables so that, for "
      "example, a problem term is counted once per report. `quarantine` keeps every rejected record with its rule; "
      "`load_run` records the raw-file checksums of the run.\n")
    rows = [[t, n(c[t])] for t in ("fact_report", "report_device", "report_problem", "report_patient_problem",
                                    "report_text", "fact_recall", "report_recall_link", "dim_manufacturer",
                                    "dim_product_code", "quarantine")]
    a(table(["Table", "Rows"], rows) + "\n")

    a("## Cleaning rules and what they caught\n")
    rq = crit["rules"]
    rows = [[k, v, n(c["quarantine_by_rule"].get(k, 0))] for k, v in {**rq["report_quarantine"], **rq["recall_quarantine"]}.items()]
    a(table(["Rule", "Quarantined when", "Records caught"], rows) + "\n")
    for src, key, rule, detail in s["quarantine"]:
        a(f"- Quarantined: `{src}` record `{key}`, rule {rule} ({detail}). This is a real report with no narrative "
          "text; Phase 1 showed '100.0% with narrative' only because one in "
          f"{n(c['raw_records'][src])} rounds away."
          if rule == "R5" else f"- Quarantined: `{src}` record `{key}`, rule {rule} ({detail}).")
    a("")
    flags = s["event_date_flag"]
    a(f"Event dates are flagged, not rejected: {n(flags.get('ok', 0))} ok, {n(flags.get('missing', 0))} missing, "
      f"{n(flags.get('after_received', 0))} after the date FDA received the report, {n(flags.get('invalid', 0))} invalid.\n")
    for prn, ini, posted in s["recalls_repaired"]:
        a(f"Recall date repaired by the registered rule: `{prn}` invalid initiation year became {ini} (posted {posted}).\n")
    a("**Privacy:** never loaded: every `manufacturer_contact_*` field and patient age, sex, weight, race and "
      "ethnicity (also removed from the quarantine copies). Patient information is limited to FDA patient-problem terms. "
      "Verifier criterion P3 checks the column names and searches loaded rows for the contact names and phone "
      "numbers of a sample of reports.\n")

    a("## Manufacturer names to parent companies\n")
    mn = s["manufacturer_names"]
    a(f"{n(mn[0])} distinct names as written by FDA map to {n(mn[1])} parent companies. Cleaning removes punctuation, "
      "site numbers and legal suffixes; then registered ownership rules merge brands into parents:\n")
    a(table(["Parent", "Names matched", "Why"], [[r["parent"], ", ".join(r["patterns"]), r["source"]]
                                                 for r in aliases["parents"]]) + "\n")
    rows = []
    for code, v in s["parents_per_code"].items():
        rows.append([code, n(v["parents"]), "; ".join(f"{p} {n(k)}" for p, k, _ in v["top"][:4]),
                     n(v["reports_under_parents_with_under_20"])])
    a(table(["Code", "Parent companies", "Largest four (reports)", "Reports under parents with < 20 reports"], rows) + "\n")
    a("**Known limitation (not fixed, to keep the registered rules intact):** a small tail of misspellings and "
      "placeholders stays separate, e.g. 'OMNI LIFE SCIECE', 'DUPUY SYNTHES JOHNSON AND JOHNSON', 'UNKNOWN'. Their "
      "volume is the last column above. A later phase may add a reviewed alias list, labelled post hoc.\n")

    a("## Report-recall links\n")
    lk = s["links"]
    rows = []
    for lt, rule in crit["rules"]["links"].items():
        v = lk[lt]
        rows.append([lt, rule, n(v["links"]), n(v["reports"]), n(v["recalls"]), n(v["median_days"]),
                     f"{n(v['min_days'])} to {n(v['max_days'])}", n(v["links_within_365_days"])])
    a(table(["Type", "Rule", "Links", "Reports", "Recalls", "Median days from recall start", "Range (days)",
             "Links within a year"], rows) + "\n")
    pp = s["pma_prefix"]
    a(f"{n(s['reports_with_any_link'])} reports have at least one link. What the numbers mean for the assistant:\n")
    a(f"- **510(k) links are broad.** A clearance number covers a device family for years, so a report can link to "
      f"recalls from long before or after it (median {n(lk['510k']['median_days'])} days apart). Phase 4 tools show "
      "only links near the report date and always say what kind of link it is.")
    no_k = [code for code in lk["firm_window"]["per_code"] if code not in lk["510k"]["per_code"]]
    if no_k:
        a(f"- **{', '.join(no_k)} ha{'s' if len(no_k) == 1 else 've'} no 510(k) links:** pacemakers are approved "
          f"through PMA ('P' numbers: {n(pp.get('P (PMA)', 0))} reports overall), and recall records list 510(k) "
          "numbers only, so they are linked only through the firm-and-time-window rule.")
    a("- **A link is context, never proof** that a report was caused by the recalled defect.\n")

    a("## Checks (criteria P1-P11)\n")
    a(table(["Criterion", "What was checked", "Result"],
            [[x["id"], x["check"], "pass" if x["pass"] else "**FAIL**"] for x in sorted(ver["checks"], key=lambda x: int(x["id"][1:]))]) + "\n")
    a("P10 (CI): the `pipeline` job in `.github/workflows/ci.yml` starts PostgreSQL, loads the committed fixture and "
      "runs the verifier on it (P1-P8), plus a test that a single tampered cell is detected. P11 was added post hoc on "
      "the Phase 2 re-check (lesson from Phase 1: compare with an outside source, not only with our own code); "
      "it compares the database with openFDA's own counts.\n")

    a("## Run it\n")
    a("```powershell\n.venv\\Scripts\\python -m mdqc.db_setup        # once: database mdqc + login mdqc_app, password into .env\n"
      ".venv\\Scripts\\python -m mdqc.load            # about 1 minute\n"
      ".venv\\Scripts\\python -m mdqc.verify_phase2 --network   # 3-4 minutes (reloads once; P11 asks openFDA)\n"
      ".venv\\Scripts\\python -m mdqc.report_phase2\n```\n")

    a("## Why we did these tasks\n")
    a(table(["Task", "Why we did it", "What we learned", "What it changes next"], [
        ["Separate database and login", "Projects must not share tables or passwords",
         "An existing admin connection can create a least-privilege login once", "Every later phase connects as mdqc_app"],
        ["Pre-registered rules before the first load", "So cleaning could not be tuned to make numbers look good",
         "The registered rules caught a real report with no narrative and repaired the 0013 recall date",
         "Rule changes from now on are labelled post hoc"],
        ["Star schema with child tables", "Counts must be right by construction (e.g. a term once per report)",
         "Repeated FDA lists (devices, terms, texts) belong in their own tables",
         "Phase 3 and the assistant's tools query clean, typed tables"],
        ["Dropped personal fields at load", "Privacy by default; the assistant never needs them",
         f"Contact names and phones were in {n(p1['overall']['reports_with_contact_fields'])} reports", "Nothing downstream can leak what was never stored"],
        ["Manufacturer parents", "Trends per company need one name per company",
         f"{n(mn[0])} spellings became {n(mn[1])} parents; a small misspelled tail remains",
         "Phase 3 signals are computed per parent company"],
        ["Report-recall links", "An investigator asks 'was there a recall for this?'",
         "510(k) links are broad in time; pacemakers can only link by firm and date",
         "Phase 4 tools filter links by date and label their strength"],
        ["Independent verifier, planted faults, tamper test", "A pipeline that cannot fail its check proves nothing",
         f"All {n(rows_checked)} rows matched; every planted fault and a single edited cell were caught",
         "CI runs the same checks on a real PostgreSQL for every push"],
    ]) + "\n")
    return "\n".join(L).rstrip() + "\n"


def main(check: bool) -> int:
    text = render()
    if check:
        same = DOC.exists() and DOC.read_text(encoding="utf-8") == text
        print("PIPELINE.md is up to date" if same else "PIPELINE.md is stale: run python -m mdqc.report_phase2")
        return 0 if same else 1
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    sys.exit(main(ap.parse_args().check))
