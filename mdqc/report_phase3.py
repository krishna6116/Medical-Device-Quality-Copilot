"""Render docs/FAILURE_MODES.md from results/phase3/ (never hand-typed numbers).

Run:  python -m mdqc.report_phase3 [--check]
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "FAILURE_MODES.md"
NAMES = {"M1": "FDA problem terms (baseline)", "M2": "Keyword rules", "M3": "Embedding vs. mode definitions",
         "M4": "Hybrid: keywords, else embedding", "M5": "TF-IDF clusters named on validation",
         "R1_bm25": "BM25 keyword search", "R2_embedding": "Embedding similarity", "R3_hybrid": "Hybrid (rank fusion)"}


def load(rel):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def n(x):
    return f"{x:,}" if isinstance(x, int) else str(x)


def pct(x, d=0):
    return f"{100 * x:.{d}f}%"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def render() -> str:
    cb, crit = load("config/failure_modes.json"), load("config/phase3_criteria.json")
    sel, ret, sig = load("results/phase3/selection.json"), load("results/phase3/retrieval.json"), load("results/phase3/signals.json")
    counts, ver = load("results/phase3/mode_counts.json"), load("results/phase3/verify_phase3.json")
    labels = list(csv.DictReader(open(ROOT / "config" / "phase3_labels.csv", encoding="utf-8")))
    spot = list(csv.DictReader(open(ROOT / "config" / "phase3_spot_check.csv", encoding="utf-8")))
    ch, t = sel["chosen"], sel["test"]
    L = []
    a = L.append
    a("# Phase 3: failure modes, similar reports, early-warning signals\n")
    a("> Generated by `python -m mdqc.report_phase3` from `results/phase3/`. Do not edit by hand.\n")
    a(f"**Scorecard: {ver['scorecard_score']}** (`config/phase3_scorecard.json`; checks that the phase was done "
      f"correctly and independently verified, with no performance target). Verifier `python -m mdqc.verify_phase3`: "
      f"{sum(c['pass'] for c in ver['checks'])}/{len(ver['checks'])} criteria pass (checked {ver['checked_utc']}).\n")
    vacc = sel["validation_accuracy"]
    if ch == "M1":
        tied = [m for m in vacc if m != "M1" and vacc[m] == vacc["M1"]]
        best_other = max((m for m in t if m != "M1"), key=lambda m: t[m]["accuracy"])
        a(f"**Result in one line:** none of the text methods beat FDA's own coded problem terms. The FDA-term baseline "
          f"(M1) {'tied ' + ', '.join(tied) + ' on validation and won the tie-break as the simpler method' if tied else 'was best on validation'} "
          f"({pct(vacc['M1'])}); on test it scored **{pct(t['M1']['accuracy'])}** (95% interval "
          f"{pct(t['M1']['accuracy_ci95'][0])}-{pct(t['M1']['accuracy_ci95'][1])}), ahead of the best text method "
          f"({best_other}, {NAMES[best_other].lower()}: {pct(t[best_other]['accuracy'])}). So the failure modes in the "
          "database come from FDA's terms mapped through the codebook.\n")
    else:
        a(f"**Result in one line:** the chosen method is **{ch} ({NAMES[ch]})** with test accuracy "
          f"**{pct(t[ch]['accuracy'])}** (95% interval {pct(t[ch]['accuracy_ci95'][0])}-{pct(t[ch]['accuracy_ci95'][1])}) "
          f"against {pct(t['M1']['accuracy'])} for the FDA-problem-term baseline; difference "
          f"{sel['chosen_vs_m1_test']['difference']:+.2f} (interval {sel['chosen_vs_m1_test']['difference_ci95'][0]:+.2f} to "
          f"{sel['chosen_vs_m1_test']['difference_ci95'][1]:+.2f}): "
          + ("the chosen method is **better** by the pre-registered rule." if sel["chosen_vs_m1_test"]["chosen_better"]
             else "**not shown to be better** by the pre-registered rule.") + "\n")

    a("## What a failure mode is, and why group reports\n")
    a("A failure mode is *how* a device failed (an implant came loose, a pod's cannula bent, a pacemaker battery "
      "ran down early). Quality engineers track complaints by failure mode because each mode has different causes "
      "and fixes. Phase 1 expected FDA's own problem terms to be too coarse (the top term for most codes says no "
      "device problem was identified), so the mode would have to be read from the narrative. Phase 3 tested that "
      "expectation"
      + (" and it did not hold: device *and patient* problem terms together, mapped through the codebook, were the "
         "best method." if ch == "M1" else " against reading the narrative.") + "\n")
    rows = []
    for fam, v in cb["families"].items():
        rows.append([fam, ", ".join(v["codes"]), ", ".join(m.split("_", 1)[1].lower().replace("_", " ") for m in v["modes"])])
    a(table(["Family", "Codes", "Modes (codebook `config/failure_modes.json`)"], rows) + "\n")

    a("## Reference labels\n")
    agree = sum(r["user_verdict"] == "agree" for r in spot)
    border = sum(r["note"].startswith("borderline") for r in labels)
    a(f"- {len(labels)} reports (40 per code) drawn by a text-blind rule; half **validation** (to choose), half **test** "
      "(scored once at the end).")
    a(f"- **Labelled by Claude (the AI assistant)** from the codebook before any method ran; {border} borderline cases "
      "carry a note. Committed before any result (criterion F1).")
    a(f"- **Spot-check: {agree}/{len(spot)} agree** (threshold 16). *Post hoc:* the user delegated the review to Claude, "
      "who re-read the 20 reports in full; this is not an independent review. The two disagreements are recorded in "
      "`config/phase3_spot_check.csv`; one shows a real limitation: labels were made from the opening part of each "
      "report, and a few legal-style reports state the reason late.")
    a("- So accuracy below means *agreement with an AI reference labeller using a written codebook*, not with a "
      "human quality engineer.\n")

    a("## Methods and results\n")
    rows = []
    for m in ["M1", "M2", "M3", "M4", "M5"]:
        rows.append([m + (" **(chosen)**" if m == ch else ""), NAMES[m], sel["chosen_settings"][m],
                     pct(sel["validation_accuracy"][m]), pct(t[m]["accuracy"]),
                     f"{pct(t[m]['accuracy_ci95'][0])}-{pct(t[m]['accuracy_ci95'][1])}", f"{t[m]['macro_f1']:.2f}",
                     " / ".join(pct(t[m]["accuracy_by_family"][f]) for f in cb["families"])])
    a(table(["", "Method", "Setting", "Validation acc.", "Test acc.", "Test 95% interval", "Test macro-F1",
             "Test acc. ortho / cardiac / diabetes"], rows) + "\n")
    a("Settings were chosen on validation only (keyword rule 'earliest' vs 'priority'; embedding threshold), from "
      f"these validation accuracies: " + ", ".join(f"{k} {pct(v)}" for k, v in sel["validation_accuracy_all_settings"].items()
                                                  if not k.startswith("M4")) + ".\n")
    a(f"Embedding model: `{sel['model']}` (revision `{sel['model_revision'][:12]}`), run locally on CPU, free.\n")
    fams = list(cb["families"])
    by = {m: t[m]["accuracy_by_family"] for m in t}
    a("**What this means** (descriptive; per-family test sets are only 20-60 reports, so these are hints, not claims):\n")
    a(f"- FDA's coded terms are a strong baseline: manufacturers already code their reports, and the codebook maps "
      f"those codes well (test {pct(t['M1']['accuracy'])}).")
    for f in fams:
        best = max(t, key=lambda m: (by[m][f], -["M1", "M2", "M3", "M4", "M5"].index(m)))
        a(f"- {f}: best on test was {best} ({pct(by[best][f])}; FDA terms {pct(by['M1'][f])}).")
    m3_all = {k: v for k, v in sel["validation_accuracy_all_settings"].items() if k.startswith("M3:")}
    a(f"- Comparing a report with one-sentence mode definitions (M3) does not work here (test {pct(t['M3']['accuracy'])}); "
      f"its thresholds made " + ("no difference on validation" if len(set(m3_all.values())) == 1 else "little difference")
      + ". Narratives are long and full of regulatory boilerplate, which a short definition does not resemble.")
    a("- A family-specific combination (e.g. keywords for pacemakers) looks promising but was not pre-registered; "
      "trying it now would be tuning on the test set, so it is left as an idea for a future, separately registered test.\n")

    a("## Failure modes across all reports (chosen method)\n")
    modes = sorted({m for v in counts.values() for m in v})
    for code, v in counts.items():
        tot = sum(v.values())
        top = sorted(v.items(), key=lambda x: -x[1])[:5]
        a(f"- **{code}** ({n(tot)} reports): " + "; ".join(f"{m} {n(c)} ({pct(c / tot)})" for m, c in top))
    a("")

    a("## Similar-report search\n")
    a("Given one report, find others with the same failure mode. Evaluated on the labelled reports: each non-'other' "
      "report is a query; the other labelled reports of the same code and split are the candidates; a candidate is "
      "relevant if it has the same reference mode. MRR = average of 1/(rank of the first relevant result).\n")
    rows = []
    for r in ("R1_bm25", "R2_embedding", "R3_hybrid"):
        rows.append([r + (" **(chosen)**" if r == ret["chosen"] else ""), NAMES[r], f"{ret['validation'][r]['mrr']:.3f}",
                     f"{ret['test'][r]['mrr']:.3f} ({ret['test'][r]['mrr_ci95'][0]:.3f}-{ret['test'][r]['mrr_ci95'][1]:.3f})",
                     f"{ret['test'][r]['p_at_5']:.2f}"])
    a(table(["", "Method", "Validation MRR", "Test MRR (95% interval)", "Test precision@5"], rows) + "\n")
    c = ret["chosen_vs_bm25_test"]
    a(f"Queries: {ret['validation']['queries']} validation, {ret['test']['queries']} test. Chosen minus BM25 on test: "
      f"{c['difference']:+.3f} (interval {c['ci95'][0]:+.3f} to {c['ci95'][1]:+.3f}): "
      + ("better by the pre-registered rule." if c["chosen_better"] else "not shown to be better by the pre-registered rule.")
      + " Phase 4's search tool uses the chosen method.\n")

    a("## Early-warning signals and the recall backtest\n")
    a(f"Rule (pre-registered): {crit['signals']['rule']}.\n")
    a(f"- **{n(sig['signals'])} signals** in 2023-2024 ({sig['signals_per_year']} per year) across "
      f"{n(sig['series_with_signal'])} of {n(sig['series'])} (code, company, mode) series. By code: "
      + ", ".join(f"{k} {n(v)}" for k, v in sorted(sig["by_code"].items())) + ".")
    a(f"- **Backtest:** {n(sig['hits'])} of {n(sig['recall_events'])} recall events initiated in 2023-2024 had a signal "
      f"for the same code and company in the 6 months before (hit rate {pct(sig['hit_rate'] or 0)}). For comparison, "
      f"{pct(sig['base_rate'])} of all 7-month windows contain a signal (base rate).")
    better = (sig["hit_rate"] or 0) > sig["base_rate"]
    a("- **Reading it honestly:** " + ("hits are more frequent than the base rate, " if better else
      "hits are not more frequent than the base rate, ") + "but there are few recall events, they cluster in a few "
      "companies, and a signal is a prompt to look, not evidence of a defect. Many recalls concern labeling, "
      "packaging or instruments that patients' reports would not show.\n")
    top = sorted(sig["signal_list"], key=lambda s: -s["count"])[:8]
    if top:
        a(table(["Code", "Company", "Mode", "Month", "Reports", "Expected"],
                [[s["code"], s["parent"], s["mode"], s["month"], n(s["count"]), s["expected"]] for s in top]) + "\n")
    hits = [e for e in sig["events"] if e["hit"]]
    if hits:
        a("Recall events with a prior signal: " + "; ".join(f"{e['code']} {e['parent']} (event {e['event']}, initiated "
                                                           f"{e['initiated']})" for e in hits[:10]) + ".\n")

    a("## Checks\n")
    a(table(["Criterion", "What was checked", "Result"],
            [[c["id"], c["check"], "pass" if c["pass"] else "**FAIL**"] for c in sorted(ver["checks"], key=lambda c: c["id"])]) + "\n")
    a(table(["Scorecard item", "Meaning", "Result"],
            [[k, v["means"], "pass" if ver["scorecard"][k] else "**FAIL**"] for k, v in load("config/phase3_scorecard.json")["items"].items()]) + "\n")
    a("**Post hoc (decided after the criteria):** the spot-check reviewer (delegated by the user to Claude); the "
      "5-item scorecard (added at the user's request, committed before any Phase 3 result).\n")

    a("## Why we did these tasks\n")
    a(table(["Task", "Why we did it", "What we learned", "What it changes next"], [
        ["Codebook before labels, labels before methods", "So neither the labels nor the methods could drift toward the other",
         "Writing definitions first forces hard choices (cause vs symptom, priority order)", "Phase 6 reuses the same labels to grade the assistant"],
        ["Five methods, chosen on validation, tested once", "To learn whether anything beats FDA's own coded terms, without fooling ourselves",
         f"{ch} won on validation; test accuracy {pct(t[ch]['accuracy'])} vs {pct(t['M1']['accuracy'])} for FDA terms",
         "Phase 4's failure-mode tool uses the chosen method"],
        ["Local embedding model", "Meaning-based grouping and search for free on a laptop",
         f"154k reports embedded on CPU; search: {ret['chosen']} chosen", "Phase 4 similar-report search runs locally at no cost"],
        ["Alert rule per company and mode, backtested", "A quality engineer wants early warning, not hindsight",
         f"{n(sig['hits'])}/{n(sig['recall_events'])} recall events had a prior signal; base rate {pct(sig['base_rate'])}",
         "Phase 7 monitoring reuses the rule on new reports; the assistant presents signals as prompts, not proof"],
        ["Independent verifier and scorecard", "Every number recomputed by separate code",
         f"Scorecard {ver['scorecard_score']}", "Same pattern for the assistant's evaluation in Phase 6"],
    ]) + "\n")
    return "\n".join(L).rstrip() + "\n"


def main(check: bool) -> int:
    text = render()
    if check:
        same = DOC.exists() and DOC.read_text(encoding="utf-8") == text
        print("FAILURE_MODES.md is up to date" if same else "FAILURE_MODES.md is stale: run python -m mdqc.report_phase3")
        return 0 if same else 1
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    sys.exit(main(ap.parse_args().check))
