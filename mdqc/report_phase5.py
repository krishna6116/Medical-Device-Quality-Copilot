"""Render docs/MEMORY.md from results/phase5/ (never hand-typed numbers).

Run:  python -m mdqc.report_phase5 [--check]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "MEMORY.md"


def load(rel):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(out + ["| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in r) + " |" for r in rows])


def quote(text):
    return "\n".join("> " + line if line.strip() else ">" for line in text.splitlines())


def render() -> str:
    crit, ver, sc = load("config/phase5_criteria.json"), load("results/phase5/verify_phase5.json"), load("results/phase5/scenarios.json")
    chk = {c["id"]: c for c in ver["checks"]}
    log = sc["log"]
    sessions = [e for e in log if e["type"] == "session"]
    L = []
    a = L.append
    a("# Phase 5: investigation memory\n")
    a("> Generated by `python -m mdqc.report_phase5` from `results/phase5/`. Do not edit by hand.\n")
    a(f"**Scorecard: {ver['scorecard_score']}** (`config/phase5_scorecard.json`, pre-registered before any memory code). "
      f"Verifier `python -m mdqc.verify_phase5`: {sum(c['pass'] for c in ver['checks'])}/{len(ver['checks'])} criteria pass "
      f"(checked {ver['checked_utc']}). Cost: $0 (no model call; scenarios use the scripted stand-in).\n")

    a("## Why memory, and why it must be deletable\n")
    a("A field-failure investigation runs for weeks. Without memory, every session starts from zero and the same causes "
      "get re-checked. With memory, the assistant starts each session knowing what was ruled out (and why), the open "
      "hypotheses, decisions and questions. In a regulated company the user must also be able to see exactly what is "
      "remembered and delete it, with no hidden copies.\n")
    d = crit["design"]
    a(table(["Design rule", "How"], [["Where", d["store"]], ["Kinds", d["kinds"]], ["Writing", d["write_path"]],
                                     ["Reading", d["read_path"]], ["Guardrails", d["guardrails"]], ["Deletion", d["deletion"]]]) + "\n")

    a("## The scenarios (real loop, real database, scripted stand-in)\n")
    a("Each scenario runs in its own database schema (`memory_scenarios`), so it never touches real investigations. "
      "The memory block shown is exactly what the session received at its start.\n")
    current = None
    for e in log:
        if e["scenario"] != current:
            current = e["scenario"]
            a(f"### Scenario {current}: {crit['scenarios'][current]}\n")
        if e["type"] == "create":
            a(f"*Investigation {e['investigation_id']} created: {e['title']} ({e['product_code']}, {e['manufacturer']}).*\n")
        elif e["type"] == "user":
            a(f"*User action (through the same API as the app and CLI): {e['action']} {json.dumps(e['args'])} -> "
              f"{e['result'].get('confirmation', json.dumps(e['result']))}*\n")
        else:
            a(f"**Session {e['session_id']} (investigation {e['investigation_id']}): \"{e['question']}\"**\n")
            a("Memory loaded at the start:\n\n```text\n" + e["memory_block"] + "\n```\n")
            saves = [t for t in e["tool_calls"] if t["name"] in ("remember", "update_memory", "forget")]
            if saves:
                a(table(["Memory call", "Result"], [[f"{t['name']} {json.dumps(t['input'])[:120]}",
                                                     json.loads(t["result"]).get("error") or json.loads(t["result"]).get("confirmation", "ok")] for t in saves]) + "\n")
            a("Answer:\n\n" + quote(e["answer"]) + "\n")

    a("## Checks\n")
    a(table(["Criterion", "What was checked", "Result"],
            [[c["id"], c["check"], "pass" if c["pass"] else "**FAIL**"] for c in sorted(ver["checks"], key=lambda c: c["id"])]) + "\n")
    a(table(["Scorecard item", "Meaning", "Result"],
            [[k, v["means"], "pass" if ver["scorecard"][k] else "**FAIL**"] for k, v in load("config/phase5_scorecard.json")["items"].items()]) + "\n")
    m2, m3, m4 = chk["M2"]["detail"], chk["M3"]["detail"], chk["M4"]["detail"]
    a(f"- **Across sessions:** {m2['blocks_matching_model']}/{m2['sessions']} session memory blocks equal an independent "
      "replay of every save, edit and deletion; the final database equals the same model.")
    a(f"- **Deletion:** {m3['texts_scanned']} deleted or refused texts ({m3['patterns_scanned']} search patterns, including the "
      f"first and last 30 characters of each) were searched in {m3['columns_scanned']} text columns: {len(m3['hits'])} hits. "
      f"Audit-trail columns: {', '.join(m3['audit_text_columns'])} (no text). The scanner's self-test catches a planted "
      "partial copy, so this check can fail.")
    probe = m4.get("api_probe", {})
    a(f"- **Guardrails:** {sum(1 for v in probe.values() if v == 'refused')} bad saves refused in the API probe "
      f"({', '.join(k for k, v in probe.items() if v == 'refused')}); in the scenarios an invented report key, a phone "
      "number and a cross-investigation delete were refused, and every save was confirmed in the answer.\n")
    a("*Post hoc (found while building, before the phase was called done):* the first version of the deletion scan only "
      "searched for whole texts and missed a planted partial copy; it now also searches the start and end of each text and "
      "self-tests on every run.\n")

    a("## Using it\n")
    a("```powershell\n.venv\\Scripts\\python -m mdqc.memory list\n.venv\\Scripts\\python -m mdqc.memory show 1\n"
      ".venv\\Scripts\\python -m mdqc.memory export 1 --md\n.venv\\Scripts\\python -m mdqc.memory delete-item 12\n"
      ".venv\\Scripts\\python -m mdqc.memory delete 1\n```\n")
    a("Phase 8's app adds a memory page with the same view, edit, export and delete actions.\n")

    a("## Limits\n")
    a("- The scenarios use the scripted stand-in, so they prove the memory machinery, not that a model uses memory wisely "
      "(saving the right things, not re-checking what was ruled out). Phase 6 measures that with the real model.")
    a("- Single-user and local: there are no accounts. A shared deployment would need per-user access control.")
    a("- Model providers keep request logs under their own retention policies; deleting memory here does not reach "
      "copies of past prompts held elsewhere. The app's cloud demo replays recordings and sends nothing.\n")

    a("## Why we did these tasks\n")
    a(table(["Task", "Why we did it", "What we learned", "What it changes next"], [
        ["Separate memory schema", "Memory must survive data reloads and stay apart from FDA data",
         "A data reload into another schema leaves memory untouched (tested)", "Phase 8's memory page reads this schema"],
        ["Explicit memory tools with confirmations", "The user must always know what was saved",
         "Every scripted save is echoed in the answer; the assistant cannot touch another investigation", "Phase 6 checks the real model confirms its saves"],
        ["Guardrails on evidence and personal data", "Memory must not hold invented evidence or personal data",
         "Invented report keys, phone numbers and emails are refused before anything is stored", "Phase 7 adds wider guardrail tests"],
        ["Real deletion with a text-free audit trail", "Deleting must leave no copy behind",
         "A deletion scan that searched whole texts missed a partial copy; it now self-tests", "Same pattern for any future store"],
        ["Independent replay of every memory action", "To prove each session saw exactly the right memory",
         f"{m2['blocks_matching_model']}/{m2['sessions']} sessions matched", "Phase 6 adds multi-session questions for the real model"],
    ]) + "\n")
    return "\n".join(L).rstrip() + "\n"


def main(check: bool) -> int:
    text = render()
    if check:
        same = DOC.exists() and DOC.read_text(encoding="utf-8") == text
        print("MEMORY.md is up to date" if same else "MEMORY.md is stale: run python -m mdqc.report_phase5")
        return 0 if same else 1
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    sys.exit(main(ap.parse_args().check))
