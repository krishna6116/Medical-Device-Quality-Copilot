"""Render docs/ASSISTANT.md from results/phase4/ (never hand-typed numbers).

Run:  python -m mdqc.report_phase4 [--check]
Phase 4 proves the pipeline with a scripted stand-in (no paid call; config/phase4_amendment.json). The live
Claude Haiku 5.5 answers to the same nine questions are recorded in the Phase 6 paid run.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from mdqc import verify_phase4 as v4
from mdqc.assistant import EFFORT, MAX_STEPS, MAX_TOKENS, MODEL, SYSTEM
from mdqc.tools import TOOL_DEFINITIONS

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "ASSISTANT.md"


def load(rel):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(out + ["| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in r) + " |" for r in rows])


def render() -> str:
    ver, summ = load("results/phase4/verify_phase4.json"), load("results/phase4/scripted_summary.json")
    qs = load("config/phase4_questions.json")["questions"]
    recs = {q["id"]: load(f"results/phase4/scripted/{q['id']}.json") for q in qs}
    chk = {c["id"]: c for c in ver["checks"]}
    est = summ["live_estimate_for_phase6"]
    L = []
    a = L.append
    a("# Phase 4: the investigation assistant\n")
    a("> Generated by `python -m mdqc.report_phase4` from `results/phase4/`. Do not edit by hand.\n")
    a(f"**Scorecard: {ver['scorecard_score']}** (`config/phase4_scorecard_v2.json`). Verifier `python -m mdqc.verify_phase4`: "
      f"{sum(c['pass'] for c in ver['checks'])}/{len(ver['checks'])} criteria pass (checked {ver['checked_utc']}).\n")
    live = load("results/phase4/verify_phase4_live.json")
    lc = {c["id"]: c for c in live["checks"]}
    lrec = {q["id"]: load(f"results/phase6/claude-haiku-5-5/{q['id']}.json") for q in qs}
    a(f"**Live answers (recorded in the Phase 6 paid run): original scorecard {live['scorecard_score']}** "
      f"(`config/phase4_scorecard.json`, criteria A1-A5, `python -m mdqc.verify_phase4 --live`, checked {live['checked_utc']}). "
      f"`{MODEL}` answered the nine questions once each for ${lc['A4']['detail']['total_usd']:.4f} in total (estimate before "
      f"the run: at most ${est['usd_max']}).\n")
    a("Phase 4 itself made no paid call (the user's decision, recorded as a *post hoc* amendment in "
      "`config/phase4_amendment.json` before any run). It proved everything around the model for free with a **scripted "
      "stand-in** (`mdqc/scripted.py`): a fixed list of tool calls per question and a template answer, run through the same "
      "loop, tools and database. The live answers were recorded later, in Phase 6, and are judged below by the original criteria.\n")
    a("## Live answers: claude-haiku-5-5 (recorded in Phase 6)\n")
    a(table(["Criterion", "What", "Result", "Detail"], [
        ["A1", "recorded tool results = fresh runs; counting tools = independent SQL", "pass" if lc["A1"]["pass"] else "**FAIL**",
         f"{lc['A1']['detail']['identical_on_rerun']}/{lc['A1']['detail']['tool_results']} identical on re-run; "
         f"independent mismatches: {len(lc['A1']['detail']['independent_mismatches'])}"],
        ["A2", "100% of citations and >= 95% of numbers traceable", "pass" if lc["A2"]["pass"] else "**FAIL**",
         f"citations {lc['A2']['detail']['citations']}, numbers {lc['A2']['detail']['numbers']} ({lc['A2']['detail']['share']:.1%})"],
        ["A3", "Q8 refers to a physician, no advice; Q9 out of scope stated", "pass" if lc["A3"]["pass"] else "**FAIL**",
         ", ".join(f"{k} {v}" for k, v in lc["A3"]["detail"].items())],
        ["A4", "cost from token usage; at most $1.00 total and $0.25 per question", "pass" if lc["A4"]["pass"] else "**FAIL**",
         f"${lc['A4']['detail']['total_usd']:.4f}"],
        ["A5", "every recording replays to the same tool calls and answer", "pass" if lc["A5"]["pass"] else "**FAIL**",
         f"{lc['A5']['detail']['cassettes']}/{lc['A5']['detail']['expected']}"]]) + "\n")
    a("Untraceable numbers: " + "; ".join(f"{q} '{s}'" for q, _, s in lc["A2"]["detail"]["misses"])
      + ". Each is the codebook's 'about 70% agreement', quoted from the system prompt rather than from a tool result.\n")
    a("**Post hoc fix to the verifier (2026-11-22, after the live run):** A1 first failed on Q3. The model asked "
      "`list_manufacturers` for battery-depletion reports only; the tool correctly returned 6,152 Boston Scientific reports "
      "(confirmed by a separate query), but the verifier's independent SQL ignored the tool's optional failure-mode and date "
      "filters and counted all 21,753 of the company's pacemaker reports. The scripted runs never used those filters, so the "
      "gap stayed hidden. The verifier now applies the same filters, and a planted wrong count (6,153) is caught. No tool "
      "and no answer changed.\n")
    a(table(["Question", "Tools the model called", "Model calls", "Cost"],
            [[q["id"], ", ".join(t["name"] for t in lrec[q["id"]]["tool_calls"]), lrec[q["id"]]["steps"],
              f"${lrec[q['id']]['cost_usd']:.4f}"] for q in qs]) + "\n")
    a("<details><summary>The model's nine answers, as recorded</summary>\n")
    for q in qs:
        a(f"**{q['id']}. {q['text']}**\n\n" + lrec[q["id"]]["answer"] + "\n")
    a("</details>\n")
    a("## Free pipeline proof (scripted stand-in, Phase 4)\n")

    a("## How it works\n")
    a(f"A quality engineer asks a question in plain English. The model (`{MODEL}`, effort {EFFORT}, up to {MAX_STEPS} calls "
      f"and {MAX_TOKENS:,} output tokens per call) decides which tools to call, reads their JSON results and answers with "
      "citations. It never writes SQL, and every number it states must appear in a tool result. Around every call the "
      "project's own loop keeps a cost ledger from the API's token counts, enforces a budget stop, and records the exchange "
      "so the demo and CI replay it for free (`python -m mdqc.replay Q1`).\n")
    a(table(["Tool", "What it does"], [[t["name"], t["description"]] for t in TOOL_DEFINITIONS]) + "\n")
    a("<details><summary>System prompt (the model's standing rules)</summary>\n\n```text\n" + SYSTEM + "\n```\n</details>\n")

    a("## The nine pre-registered questions, run by the scripted stand-in\n")
    per = chk["B3"]["detail"]["per_question"]
    rows = [[q["id"], q["kind"], ", ".join(t["name"] for t in recs[q["id"]]["tool_calls"]) or "none (refusal / scope)",
             per[q["id"]]["citations"], per[q["id"]]["numbers"]] for q in qs]
    a(table(["", "Kind", "Tools called", "Citations traced", "Numbers traced"], rows) + "\n")
    for q in qs:
        r = recs[q["id"]]
        a(f"### {q['id']}. {q['text']}\n")
        a("\n".join("> " + line if line.strip() else ">" for line in r["answer"].splitlines()) + "\n")

    a("## Checks\n")
    a(table(["Criterion", "What was checked", "Result"],
            [[c["id"], c["check"], "pass" if c["pass"] else "**FAIL**"] for c in sorted(ver["checks"], key=lambda c: c["id"])]) + "\n")
    a(table(["Scorecard item", "Meaning", "Result"],
            [[k, v["means"], "pass" if ver["scorecard"][k] else "**FAIL**"] for k, v in load("config/phase4_scorecard_v2.json")["items"].items()]) + "\n")
    b1 = chk["B1"]["detail"]
    if "stress_inputs" in b1:
        a(f"*Re-check (post hoc, 2026-11-22):* a stress test with odd inputs found that the tools could crash on a "
          "malformed date or limit, accepted failure modes from another device family, and silently moved recall "
          "dates before 2022 into the report window (a wrong answer with no error). All were fixed and B1 now includes "
          f"a {b1['stress_inputs']}-input stress suite: every odd input returns an error result the model can act on, "
          f"nothing crashes, the database connection stays usable, and an older-recall question returns "
          f"{b1['old_recalls_2015_16'][0]} records, equal to independent SQL.\n")
    b3 = chk["B3"]["detail"]
    a("The grounding checker accepted every scripted answer and caught every planted error ("
      + ", ".join(k for k, v in b3["planted_caught"].items() if v) + "). The safety checker flagged planted advice and "
      "accepted a planted referral. Phase 6 applies the same checkers to the model's real answers.\n")
    a(f"Cost: the scripted runs cost $0 (no model). The ledger matches an independent formula, including cache writes, "
      f"cache reads and prompts over 100K tokens. Upper-bound estimate for the nine live questions in Phase 6: "
      f"${est['usd_max']} ({est['calls_max']} calls at most).\n")

    a("## What the tools already show (real data, through the scripted run)\n")
    a("These facts come from the tool results, not from a model, so they hold whatever the model later does with them:\n")
    for qid in ("Q1", "Q3", "Q4", "Q7"):
        a(f"- {qid}: " + recs[qid]["answer"].split("\n", 1)[1])
    a("")

    a("## Limits\n")
    a("- The scripted stand-in shows the plumbing works; it says nothing about how well a model chooses tools or reads results. That is Phase 6.")
    a("- Grounding checks that numbers and citations come from the tools, not that the answer is right; Phase 6 adds gold answers.")
    a("- Failure modes come from FDA problem terms (about 70% agreement with reference labels, Phase 3), so a report's mode can disagree with its narrative.\n")

    a("## Why we did these tasks\n")
    a(table(["Task", "Why we did it", "What we learned", "What it changes next"], [
        ["Fixed, read-only tools instead of free SQL", "The model can only ask questions we have tested",
         "Eight tools cover counts, trends, modes, search, reports, recalls and signals; all match independent SQL", "Phase 5 adds memory tools the same way"],
        ["Our own agent loop with a ledger and budget stop", "Cost must be known and capped around every call",
         "The ledger matches an independent formula; the budget, refusal and step limits work (fake-model tests)", "Phase 6's paid run uses this loop unchanged"],
        ["Deferring the paid run to Phase 6 (post hoc)", "The user wants a single paid run for the whole project",
         "A scripted stand-in proves the pipeline end to end for $0", "Phase 6 runs the nine questions live with the evaluation"],
        ["Grounding and safety checkers", "An answer is only useful if every number and citation can be traced",
         "The checkers pass correct answers and catch planted invented numbers, keys and recalls", "Phase 6 applies them to the model's answers"],
        ["Recording and replay", "The demo and CI must cost nothing and never change", "Every recording replays identically offline",
         "Phase 8's app replays the Phase 6 recordings"],
    ]) + "\n")
    return "\n".join(L).rstrip() + "\n"


def main(check: bool) -> int:
    text = render()
    if check:
        same = DOC.exists() and DOC.read_text(encoding="utf-8") == text
        print("ASSISTANT.md is up to date" if same else "ASSISTANT.md is stale: run python -m mdqc.report_phase4")
        return 0 if same else 1
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    sys.exit(main(ap.parse_args().check))
