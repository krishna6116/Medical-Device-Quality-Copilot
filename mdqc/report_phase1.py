"""Render docs/EDA_FINDINGS.md from the Phase 1 results files (never hand-typed numbers).

Run:  python -m mdqc.report_phase1           write the doc
      python -m mdqc.report_phase1 --check   exit 1 if the doc on disk differs from a fresh render

Sources: config/scope.json, config/phase1_criteria.json, results/phase1/eda_summary.json,
results/phase1/download_manifest.json, results/phase1/verify_phase1.json.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "EDA_FINDINGS.md"


def load(rel: str) -> dict:
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def n(x) -> str:
    if isinstance(x, float):
        return f"{int(x):,}" if x.is_integer() else f"{x:,.1f}"
    return f"{x:,}" if isinstance(x, int) else str(x)


def pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}%"


def table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def render() -> str:
    scope, crit = load("config/scope.json"), load("config/phase1_criteria.json")
    s, man, ver = (load("results/phase1/eda_summary.json"), load("results/phase1/download_manifest.json"),
                   load("results/phase1/verify_phase1.json"))
    codes, pc = s["codes"], s["per_code"]
    fam = {c: scope["product_codes"][c]["family"] for c in codes}
    name = {c: scope["product_codes"][c]["device_name"] for c in codes}
    w = scope["event_window"]
    window = f"{w['from'][:4]}-{w['from'][4:6]}-{w['from'][6:]} to {w['to'][:4]}-{w['to'][4:6]}-{w['to'][6:]}"
    ov = s["overall"]
    passed = sum(c["pass"] for c in ver["checks"] if c["id"] != "info")
    total_checks = sum(1 for c in ver["checks"] if c["id"] != "info")
    L = []
    a = L.append

    a("# Phase 1 findings: openFDA device data (exploratory analysis)\n")
    a("> Generated by `python -m mdqc.report_phase1` from `results/phase1/`. Do not edit by hand.\n")
    a(f"**Scope (pre-registered {scope['registered_on']}, `config/scope.json`):** {len(codes)} FDA product codes, "
      f"adverse-event reports received {window}, plus every recall for those codes. "
      f"**{n(ov['reports'])} reports** ({n(ov['distinct_report_keys_across_codes'])} distinct report keys) and "
      f"**{n(ov['recalls'])} recall records**.\n")
    a(f"**Verification:** `python -m mdqc.verify_phase1` recomputes every number below from the raw files with "
      f"separate standard-library code: **{passed}/{total_checks} checks pass** "
      f"(evidence `results/phase1/verify_phase1.json`, checked {ver['checked_utc']}).\n")
    a("**Read every count with this in mind:** a MAUDE report says a device *may* have been involved in an event. "
      "Reports are not confirmed failures, are not proof of cause, and there is no count of devices in use, "
      "so report counts are signals, never failure rates. Large companies sell more devices and must report, "
      "so they appear more often for that reason alone.\n")

    a("## The data\n")
    rows = [[c, fam[c], name[c], n(pc[c]["reports"]), n(pc[c]["q6_recalls"]),
             man["events"][c]["server_last_updated"]] for c in codes]
    a(table(["Code", "Family", "FDA device name", "Reports", "Recalls (all years)", "openFDA data as of"], rows) + "\n")

    a("## What stands out\n")
    implants = [c for c in codes if fam[c] in ("orthopedic", "cardiac")]
    pumps = [c for c in codes if c not in implants]
    share = lambda c, t: pc[c]["q2_event_type"].get(t, 0) / pc[c]["reports"]  # noqa: E731
    a("1. **Implants and pumps report differently.** Implant reports are mostly classed as injuries ("
      + ", ".join(f"{c} {pct(share(c, 'Injury'), 0)}" for c in implants) + "), because an implant problem that "
      "leads to another operation is reported as an injury; insulin pump reports are mostly malfunctions ("
      + ", ".join(f"{c} {pct(share(c, 'Malfunction'), 0)}" for c in pumps)
      + "). Raw counts must not be compared across device families.")
    generic = "Adverse Event Without Identified Device or Use Problem"
    gen_top = [c for c in codes if pc[c]["q3_top_problems"] and pc[c]["q3_top_problems"][0][0] == generic]
    a(f"2. **FDA problem codes are coarse.** The top term for {len(gen_top)} of {len(codes)} codes is "
      f"\"{generic}\" (" + ", ".join(
          f"{c} {pct(pc[c]['q3_top_problems'][0][1] / pc[c]['reports'], 0)} of reports" for c in gen_top)
      + "). The failure mode is in the narrative text, which every report has (median length "
      + ", ".join(f"{c} {n(pc[c]['q5_narrative_len_median'])}" for c in codes) + " characters). So Phase 3 "
      "groups failure modes from the text, with the FDA codes only as a weak baseline.")
    a("3. **One manufacturer often dominates a code.** Largest share: " + "; ".join(
      f"{c} {pc[c]['q4_top_manufacturers'][0][0]} {pct(pc[c]['q4_top_manufacturer_share'], 0)}" for c in codes)
      + ". Counts mostly reflect market share and reporting practice, so trends are read per manufacturer.")
    spiky = [c for c in codes if pc[c]["q1_spike_months_over_3x_median"]]
    ratio = max(pc[c]["q1_monthly_max"] / pc[c]["q1_monthly_median"] for c in codes)
    a("4. **No extreme monthly spikes**" + (f" except in {', '.join(spiky)}" if spiky else
      " (no month above 3x its code's median)") + f". The busiest month was at most {ratio:.1f}x its code's "
      "median, so Phase 3's signal rule must detect smaller shifts than a spike filter would.")
    a("5. **Recalls concentrate in the knees.** Recall records initiated in the report window: " + ", ".join(
      f"{c} {n(pc[c]['q6_recalls_in_window'])}" for c in codes) + ". The pacemaker and insulin pump codes have "
      "few recalls in the window, so backtesting signals against recalls will rest mainly on the orthopedic codes.")
    a("6. **Implant reports arrive late.** Median lag from event to FDA receipt: " + ", ".join(
      f"{c} {n(pc[c]['q7_lag_median_days'])} days" for c in codes) + "; 90th percentile up to "
      f"{n(max(pc[c]['q7_lag_p90_days'] for c in codes))} days. Recent months always look quieter than they "
      "will once late reports arrive, so drift monitoring (Phase 7) must allow for that.")
    years = sorted({m[:4] for m in s["months"]})
    y0, y1 = years[0], years[-1]

    def change(code, maker):
        by = pc[code]["q9_top3_by_year"][maker]
        return (by[y1] - by[y0]) / by[y0] if by[y0] else float("inf")

    moves = []
    for c in codes:
        m = max(pc[c]["q9_top3_by_year"], key=lambda k: (abs(change(c, k)), k))
        by = pc[c]["q9_top3_by_year"][m]
        moves.append(f"{c} {m.title()} {n(by[y0])} to {n(by[y1])} ({change(c, m):+.0%})")
    a(f"7. **Totals hide manufacturer shifts (Q9, post hoc).** Largest {y0}-to-{y1} change among each code's "
      "three biggest manufacturers: " + "; ".join(moves) + ". A flat code-level line can hide one maker rising "
      "while another falls, so Phase 3's signal rule works per manufacturer.\n")

    a("## Checks (criteria C1-C8)\n")
    rows = []
    for c in sorted(ver["checks"], key=lambda c: c["id"]):
        if c["id"] != "info":
            rows.append([c["id"], c["check"], "pass" if c["pass"] else "**FAIL**"])
    a(table(["Criterion", "What was checked", "Result"], rows) + "\n")
    a(f"Every downloaded count equals the server's total for the same search at the moment of download. "
      f"Raw files: `data/raw/` ({len(man['files'])} files, "
      f"{sum(f['bytes'] for f in man['files'].values()) / 1e6:.1f} MB compressed), pinned by "
      f"`data/checksums.sha256`. {n(ov['reports_with_contact_fields'])} reports carry manufacturer contact names "
      f"or phone numbers; Phase 2 drops those fields before anything is loaded or indexed.\n")

    a("## Q1. Monthly report volume\n")
    a("![Reports received per month](figures/phase1/monthly_reports.png)\n")
    rows = [[c, n(pc[c]["reports"]), f"{pc[c]['q1_monthly_median']:,.1f}",
             f"{n(pc[c]['q1_monthly_max'])} ({pc[c]['q1_monthly_max_month']})",
             ", ".join(f"{m} ({n(v)})" for m, v in pc[c]["q1_spike_months_over_3x_median"].items()) or "none"]
            for c in codes]
    a(table(["Code", "Reports", "Median per month", "Busiest month", "Months > 3x median"], rows) + "\n")

    a("## Q2. Event type\n")
    a("![Event type mix](figures/phase1/event_type_mix.png)\n")
    types = ["Malfunction", "Injury", "Death", "Other", "(blank)"]
    rows = []
    for c in codes:
        et, tot = pc[c]["q2_event_type"], pc[c]["reports"]
        rest = tot - sum(et.get(t, 0) for t in types)
        rows.append([c] + [f"{n(et.get(t, 0))} ({pct(et.get(t, 0) / tot)})" for t in types] + [n(rest)])
    a(table(["Code"] + types + ["Other labels"], rows) + "\n")

    a("## Q3. Most common FDA problem terms (number of reports listing each term, top 10 per code)\n")
    for c in codes:
        top = pc[c]["q3_top_problems"]
        a(f"**{c} ({fam[c]})**: " + "; ".join(f"{p} {n(k)}" for p, k in top) +
          f". Reports with no problem term: {n(pc[c]['q3_reports_without_problem_terms'])}.\n")
    a("*Correction (post hoc, 2026-11-21):* openFDA lists most problem terms twice inside one report. The first "
      "version of this doc counted list entries, which roughly doubled every term count (and overstated, for "
      "example, the share of hip reports carrying the generic term). Both the analysis and the verifier used the "
      "same wrong definition, so they agreed; a third check against openFDA's own server-side counts (verifier "
      "criterion C8, `--network`) exposed it. Terms are now counted once per report and match the server exactly.\n")

    a("## Q4. Manufacturers\n")
    rows = [[c, n(pc[c]["q4_distinct_manufacturers"]), pct(pc[c]["q4_top_manufacturer_share"]),
             "; ".join(f"{m} {n(k)}" for m, k in pc[c]["q4_top_manufacturers"])] for c in codes]
    a(table(["Code", "Distinct manufacturers", "Largest one's share", "Top 5 (reports)"], rows) + "\n")
    a("Manufacturer names are written as reported: one company can appear under several names (site names, "
      "or an acquired brand: St. Jude Medical has been part of Abbott since 2017, yet both names appear for LWP). "
      "Phase 2 normalises them.\n")

    a("## Q9. Monthly trend of the three largest manufacturers (post hoc)\n")
    a("*Added on the Phase 1 re-check:* the plan asked for trends per manufacturer, but the pre-registered "
      "questions Q1-Q8 did not include them. Recomputed independently by the verifier like every other number.\n")
    a("![Top manufacturers per month](figures/phase1/manufacturer_trends.png)\n")
    years = sorted({m[:4] for m in s["months"]})
    rows = []
    for c in codes:
        busiest = pc[c]["q1_monthly_max_month"]
        for m, by in pc[c]["q9_top3_by_year"].items():
            ch = (by[years[-1]] - by[years[0]]) / by[years[0]] if by[years[0]] else None
            rows.append([c, m] + [n(by[y]) for y in years] + [f"{ch:+.0%}" if ch is not None else "n/a",
                        f"{n(pc[c]['q9_busiest_month_by_maker'][m])} of {n(pc[c]['q1_monthly_max'])} ({busiest})"])
    a(table(["Code", "Manufacturer"] + years + [f"Change {years[0]}-{years[-1]}", "In the code's busiest month"],
            rows) + "\n")

    a("## Q5. Narrative text\n")
    rows = [[c, pct(pc[c]["q5_share_with_narrative"]), n(pc[c]["q5_narrative_len_median"]),
             n(pc[c]["q5_narrative_len_p90"])] for c in codes]
    a(table(["Code", "Reports with narrative", "Median length (characters)", "90th percentile"], rows) + "\n")

    a("## Q6. Recalls\n")
    a("![Recalls per year](figures/phase1/recalls_per_year.png)\n")
    rows = [[c, n(pc[c]["q6_recalls"]), n(pc[c]["q6_recall_events_distinct"]), n(pc[c]["q6_recalls_in_window"]),
             "; ".join(f"{k} {n(v)}" for k, v in list(pc[c]["q6_recalls_by_root_cause"].items())[:3])] for c in codes]
    a(table(["Code", "Recall records", "Distinct recall events", f"Initiated {w['from'][:4]}-{w['to'][:4]}",
             "Top root causes"], rows) + "\n")
    a("One recall event (one firm action) often covers several products, so it produces several recall records.\n")
    bad = {c: pc[c]["q6_recalls_invalid_initiation_date"] for c in codes if pc[c]["q6_recalls_invalid_initiation_date"]}
    a("*Post hoc data rule:* a recall whose initiation year is missing or before 1976 (when FDA device regulation "
      "began) is treated as an invalid date, counted here and left out of the by-year counts. The verifier found "
      "this after the download: " + (", ".join(f"{c} {n(v)}" for c, v in bad.items()) or "none") +
      " (a knee recall dated '0013-11-26' but posted 2013-12-13: a typo for 2013). Phase 2 may repair such "
      "dates from the posted date; Phase 1 reports them as they are.\n")

    a("## Q7. Reporting lag (date received minus date of event)\n")
    rows = [[c, n(pc[c]["q7_lag_reports_with_both_dates"]), n(pc[c]["q7_lag_median_days"]),
             n(pc[c]["q7_lag_p90_days"]), n(pc[c]["q7_lag_negative"])] for c in codes]
    a(table(["Code", "Reports with both dates", "Median lag (days)", "90th percentile (days)",
             "Event date after received date"], rows) + "\n")

    a("## Q8. Multi-device reports\n")
    rows = [[c, n(pc[c]["q8_multi_device_reports"]), n(pc[c]["q8_listed_under_other_scope_code"])] for c in codes]
    a(table(["Code", "Reports listing more than one device", "Also listed under another of our codes"], rows) + "\n")

    a("## Why we did these tasks\n")
    a(table(["Task", "Why we did it", "What we learned", "What it changes next"], [
        ["Pre-registered the scope before downloading", "So the data could not be picked to flatter results",
         "Infusion pumps alone would have been ~7x the download and dominated by one manufacturer",
         "Every later phase uses exactly these 5 codes and this window"],
        ["Compared every count with the server's own total", "To prove nothing was lost or doubled while paging",
         "All counts matched exactly, zero duplicates", "Phase 2 can treat the raw files as the single source"],
        ["Checksums on the raw files", "To pin our copy (openFDA changes weekly)",
         "gzip embeds a file name and time; writing neither makes checksums reproducible",
         "Later phases check they read the same bytes"],
        ["Answered the pre-registered questions Q1-Q8", "To learn the data's shape before modelling",
         "Problem codes are coarse, narratives are rich, one maker often dominates, implant reports arrive late",
         "Phase 3 groups failure modes from text; trends per manufacturer; drift checks allow for lag"],
        ["Independent verifier", "So a bug in the analysis cannot pass silently",
         "It caught a recall dated year 0013 that the two implementations handled differently",
         "Phase 2 adds date validation and repair rules for recall dates"],
        ["Cross-check against openFDA's own server counts", "Two programs can share the same wrong definition",
         "Problem terms are repeated inside reports; our counts were doubled until this check",
         "Every later verifier also compares with an outside source, not only with itself"],
        ["Per-manufacturer trends (Q9, post hoc)", "The plan asked for them; code totals can hide makers",
         "Makers move in opposite directions inside one code (e.g. one knee maker +253% while others stay flat)",
         "Phase 3 signals are computed per manufacturer; Phase 2 merges brand names like St. Jude / Abbott"],
    ]) + "\n")
    return "\n".join(L).rstrip() + "\n"


def main(check: bool) -> int:
    text = render()
    if check:
        same = DOC.exists() and DOC.read_text(encoding="utf-8") == text
        print("EDA_FINDINGS.md is up to date" if same else "EDA_FINDINGS.md is stale: run python -m mdqc.report_phase1")
        return 0 if same else 1
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    sys.exit(main(ap.parse_args().check))
