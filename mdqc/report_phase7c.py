"""Phase 7c report: docs/DATA_2025_2026.md, generated from results/phase7c/.   Run: python -m mdqc.report_phase7c [--check]
--check also re-grades the recorded answers (no database, no API)."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from mdqc.report_phase7 import load, table

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "DATA_2025_2026.md"


def render() -> str:
    v, m, a, e, l_ = (load(f"results/phase7c/{x}.json") for x in ("verify_phase7c", "model_check", "analytics_summary", "embed_summary", "load_summary"))
    c = l_["counts"]
    cats: dict = {}
    for r in m["rows"]:
        k = cats.setdefault(r["category"], [0, 0])
        k[0] += r["correct"]
        k[1] += 1
    return "\n".join([
        "# Phase 7c: reports from 2025-2026, and letting the assistant use them", "", "_Generated by `python -m mdqc.report_phase7c` from `results/phase7c/`. Do not edit by hand._", "",
        f"**Result: checks {v['passed']}; Haiku answered {m['correct']} questions correctly** (bar {m['bar']}; 95% interval {100 * m['ci95'][0]:.0f}% to {100 * m['ci95'][1]:.0f}%), for ${m['usd']:.4f}.", "",
        f"Schema `core_all` holds {c['fact_report']:,} reports (2022 to mid-November 2026) and {c['fact_recall']:,} recalls; `core` (2022-2024) and everything built on it is unchanged. "
        f"{a['signals']} early-warning signals ({a['signals_2022_2024']} of them in 2022-2024, as before); {e['rows']:,} reports can be searched by text.", "",
        "## What the assistant can reach", "",
        table(["", "Default scope", "Scope 'all'"], [["Reports", "2022-2024", "2022 to mid-November 2026"], ["Narrative", "first 1,500 characters", "all of it, in parts of 3,000"],
                                                    ["Recalls and similar reports", "first 10", "pages of 10, up to 110 in"], ["SQL written by the model", "no", "no"],
                                                    ["Contact details, other investigations' memory", "no", "no"], ["Writing during a lookup", "refused by the database", "refused by the database"]]), "",
        "## Independent checks", "", table(["Check", "What", "Result"], [[x["id"], x["check"], "pass" if x["pass"] else "**FAIL**"] for x in v["checks"]]), "",
        "Rows are rebuilt from the raw files by separate code from the same author as the loader.", "",
        "## Model check (20 questions, one run on Claude Haiku 5.5, answers fixed first)", "", table(["Kind", "Correct"], [[k, f"{x[0]}/{x[1]}"] for k, x in cats.items()]), "",
        "All 20 answers were also read (by Claude, not independently). C11 is correct but adds a false remark: it implies the 1,536 unidentified reports outnumber the 1,710 coded as instability. The grader does not check such asides.", "",
        "## Changes after the pre-registration (post hoc, before any check)", "",
        "- The first load rejected 3,663 reports without a narrative, almost all from July-October 2026, because FDA had not published the text yet. Reports from 2025 on are loaded without it: counted, but not searchable by text.",
        "- One combined schema replaced the planned separate one, so company names and recall links are consistent.",
        "- Before any answer existed, three questions that could be guessed (boilerplate numbers, an answer of 1) were replaced and one of 21 was dropped.", "",
        "## Limits", "",
        "- 2022-2024 reports come from a snapshot of 2026-11-21 and later ones from 2026-11-25; FDA edits to older reports since then are missing. 2026Q4 is incomplete and recent months will grow.",
        "- Failure modes agreed with reference labels on about 70% of 2022-2024 test reports; they were not re-validated on 2025-2026.",
        "- Earlier accuracy (78/80) and the Phase 7b guard result were measured on 2022-2024 and the default tools; they do not carry over. The guard was not tested on scope 'all'.",
        "- 20 questions are few, mostly direct lookups, and written by the author of the tools.",
        "- A few narratives are data dumps (the longest has 10.1 million characters, 3,375 parts); the assistant makes at most 10 model calls, so it can only read part of those.",
        "- The Phase 7 drift vocabulary check for 2026Q3 read about a quarter fewer narratives than reports.", "",
        "## Why we did these tasks", "", table(["Task", "Why we did it", "What we learned", "What it changes next"], [
            ["Fingerprinted the old tables", "To prove nothing finished was disturbed", "18 tables identical afterwards", "Same for any later load"],
            ["Kept the old scope as default", "Recorded answers must still replay", "233 of 233 recorded lookups identical", "Phase 8 can offer both scopes"],
            ["Asked why reports were rejected", "3,663 was far from the usual 1", "FDA publishes the text months after the rest", "Recent counts include them; text search says how many it cannot see"],
            ["Rebuilt every row from raw", "A load can be wrong without failing", "0 differences in 233,264 reports", "Runs again after any reload"],
            ["Questions that need paging", "To test the new access, not just old lookups", "Haiku paged correctly in all four", "Harder analysis questions would be the next test"]]), ""])


def main(check: bool) -> int:
    doc = render()
    if check:
        from mdqc import eval7c

        pub = {r["id"]: r["correct"] for r in load("results/phase7c/model_check.json")["rows"]}
        re_ = {q["id"]: eval7c.check(q, load(f"results/phase7c/answers/{q['id']}.json"))[0] for q in eval7c.questions()}
        ok = DOC.exists() and DOC.read_text(encoding="utf-8") == doc and pub == re_
        print("DATA_2025_2026.md is " + ("up to date and the answers re-grade the same" if ok else "stale, or the grades differ"))
        return 0 if ok else 1
    DOC.write_text(doc, encoding="utf-8", newline="\n")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    sys.exit(main(ap.parse_args().check))
